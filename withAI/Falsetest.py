if __name__ == "__main__":
    # ------------ 准备待处理的任务列表（替换成你的实际任务数据，如批量数据、用户请求等）------------
    # 格式：[(任务1参数1, 任务1参数2), (任务2参数1, 任务2参数2), ...]
    task_list = [
        ("任务A", 100),    # 正常参数（预期成功）
        (200, 300),        # 参数1类型合法（int），参数2正常（预期成功）
        ("任务B", -50),    # 参数2负数（预期抛出ValueError）
        (None, 200),       # 参数1为None（预期抛出TypeError）
        ("任务C", None),   # 参数2为None（预期抛出ValueError）
        ("任务D", 500),    # 正常参数（预期成功）
    ]

    print("=== 开始批量处理任务（异常任务会提示，程序不退出）===\n")
    
    # ------------ 循环处理每个任务（核心：逐个捕获异常，不影响整体流程）------------
    for task_idx, (param1, param2) in enumerate(task_list, 1):
        print(f"【第{task_idx}个任务】")
        try:
            # ------------ 可能触发 raise 的代码：包裹业务函数调用 ------------
            result = process_task(param1, param2)
            # 任务成功：处理结果（替换成你的成功逻辑，如打印、存储结果等）
            print(f"✅ 处理成功：{result}\n")
        
        # ------------ 捕获函数中主动 raise 的异常（按异常类型精准捕获，避免吞掉未知异常）------------
        except TypeError as e:
            # 处理“类型错误”（对应函数中 raise TypeError 的场景）
            print(f"❌ 处理失败（类型错误）：{e}\n")
        except ValueError as e:
            # 处理“值错误”（对应函数中 raise ValueError 的场景）
            print(f"❌ 处理失败（值错误）：{e}\n")
        except Exception as e:
            # 可选：捕获其他未预期的异常（建议保留，避免程序因未知异常退出）
            print(f"❌ 处理失败（未知错误）：{str(e)}\n")
        
        # ------------ 无论成功/失败，都会执行后续代码（证明程序不退出）------------

    # ------------ 所有任务处理完毕，程序继续执行后续逻辑 ------------
