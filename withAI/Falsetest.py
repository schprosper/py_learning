"""
通用模板核心逻辑：
1. 定义业务处理函数：在函数内部做「条件校验/风险操作」，不满足要求时主动 raise 异常（告知问题）
2. 调用层：用 try-except 包裹函数调用，捕获异常后仅处理（打印/记录），不终止程序
3. 循环/批量场景：即使单个任务失败，后续任务依然执行（体现“不退出”核心）
"""

# ---------------------- 第一步：定义通用业务处理函数（内部主动抛异常）----------------------
def process_task(task_param1, task_param2, *args, **kwargs):
    """
    通用业务处理函数：替换成你的实际业务逻辑（如数据校验、文件操作、接口调用等）
    :param task_param1: 业务参数1（根据实际需求修改参数名和类型）
    :param task_param2: 业务参数2（可扩展更多参数）
    :param args: 可变位置参数（可选，根据业务需要添加）
    :param kwargs: 可变关键字参数（可选，根据业务需要添加）
    :return: 处理结果（根据业务返回对应数据，无返回则省略）
    """
    # ------------ 关键1：业务校验/风险操作（不满足条件则主动 raise 异常）------------
    # 校验1：参数1的合法性（替换成你的实际校验条件，如类型、非空、范围等）
    if not isinstance(task_param1, (str, int)):  # 示例：参数1必须是字符串或整数
        # raise 异常类型(错误信息)：主动告知调用层“这里出问题了”
        raise TypeError(f"参数1[{task_param1}]类型非法！要求 str/int 类型")
    
    # 校验2：参数2的合法性（替换成你的实际校验条件，如非负、非空等）
    if task_param2 is None or task_param2 < 0:  # 示例：参数2不能为None或负数
        raise ValueError(f"参数2[{task_param2}]非法！要求非空且非负")
    
    # ------------ 关键2：正常业务逻辑（只有所有校验通过才执行）------------
    # 替换成你的实际业务操作（如计算、数据存储、接口请求等）
    process_result = f"参数1={task_param1}, 参数2={task_param2} → 处理成功"
    return process_result


